using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using Content.Shared.PlantAnalyzer;

namespace Content.Client.Botany.Ui;

[GenerateTypedNameReferences]
public sealed partial class PlantAnalyzerWindow : FancyWindow
{
    public PlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
    }

public void DisplayInfo(PlantAnalyzerScannedMessage msg)
{
    var text = new FormattedMessage();

    text.AddMarkup($"[color=yellow][SCANNER DE PLANTAS][/color]\n");

    if (msg.IsPlant)
        text.AddMarkup("\n[INFORMAÇÕES DA PLANTA]\n");
    else
        text.AddMarkup("\n[INFORMAÇÕES DA SEMENTE]\n");

    var seed = msg.Seed;
    text.AddMarkup($"Nome: {seed.Name}\n");
    text.AddMarkup($"Nome de Exibição: {seed.DisplayName}\n");
    text.AddMarkup($"Tipo: {seed.Noun}\n");

    text.AddMarkup("\n[GENÉTICA]\n");
    text.AddMarkup($"- Potência: {seed.Potency}\n");
    text.AddMarkup($"- Rendimento: {seed.Yield}\n");
    text.AddMarkup($"- Maturação: {seed.Maturation} ciclos\n");
    text.AddMarkup($"- Vida Máxima: {seed.Endurance}\n");
    text.AddMarkup($"- Tempo de Vida: {seed.Lifespan} ciclos\n");
    text.AddMarkup($"- Produção: {seed.Production}\n");
    text.AddMarkup($"- Pode gerar sementes: {(seed.Seedless ? "Não" : "Sim")}\n");

    if (msg.IsPlant && msg.Holder is { } holder)
    {
        text.AddMarkup("\n[STATUS DA PLANTA]\n");
        text.AddMarkup($"- Saúde: {holder.Health}/{seed.Endurance}\n");
        text.AddMarkup($"- Idade: {holder.Age} ciclos\n");
        text.AddMarkup($"- Pronta para colheita: {(holder.HarvestReady ? "Sim" : "Não")}\n");
        text.AddMarkup($"- Amostrada: {(holder.Sampled ? "Sim" : "Não")}\n");
        text.AddMarkup($"- Estado: {(holder.Dead ? "Morta" : "Saudável")}\n");
        text.AddMarkup($"- Viabilidade Genética: {(seed.Viable ? "Saudável" : "Defeituosa")}\n");

        text.AddMarkup("\n[CONDIÇÕES DO VASO]\n");
        text.AddMarkup($"- Água no vaso: {holder.WaterLevel}/100\n");
        text.AddMarkup($"- Nutrientes no vaso: {holder.NutritionLevel}/100\n");
        text.AddMarkup($"- Toxinas acumuladas: {holder.Toxins}\n");
        text.AddMarkup($"- Infestação de pragas: {holder.PestLevel}\n");
        text.AddMarkup($"- Ervas daninhas: {holder.WeedLevel}\n");

        text.AddMarkup("\n[AVISOS AMBIENTAIS]\n");
        text.AddMarkup($"- Temperatura: {(holder.ImproperHeat ? "Incorreta" : "OK")}\n");
        text.AddMarkup($"- Pressão: {(holder.ImproperPressure ? "Incorreta" : "OK")}\n");
        text.AddMarkup($"- Luz: {(holder.ImproperLight ? "Incorreta" : "OK")}\n");
    }

    text.AddMarkup("\n[CONSUMO]\n");
    text.AddMarkup($"- Água: {seed.WaterConsumption} por ciclo\n");
    text.AddMarkup($"- Nutrientes: {seed.NutrientConsumption} por ciclo\n");

    text.AddMarkup("\n[TOLERÂNCIAS]\n");
    text.AddMarkup($"- Luz: Ideal {seed.IdealLight} ± {seed.LightTolerance}\n");
    text.AddMarkup($"- Temperatura: Ideal {seed.IdealHeat} ± {seed.HeatTolerance}\n");
    text.AddMarkup($"- Pressão: {seed.LowPressureTolerance} - {seed.HighPressureTolerance} kPa\n");
    text.AddMarkup($"- Toxinas: até {seed.ToxinsTolerance}\n");
    text.AddMarkup($"- Pragas: até {seed.PestTolerance}\n");
    text.AddMarkup($"- Ervas daninhas: até {seed.WeedTolerance}\n");

    text.AddMarkup("\n[QUÍMICOS]\n");
    if (seed.Chemicals.Count > 0)
    {
        foreach (var chem in seed.Chemicals)
            text.AddMarkup($"- {chem.Id} (Min: {chem.Min}, Max: {chem.Max}, PotDiv: {chem.PotDiv})\n");
    }
    else
    {
        text.AddMarkup("Nenhum químico presente.\n");
    }

    text.AddMarkup("\n[MUTAÇÕES ATIVAS]\n");
    if (seed.Mutations.Count > 0)
    {
        foreach (var mut in seed.Mutations)
            text.AddMarkup($"- {mut}\n");
    }
    else
    {
        text.AddMarkup("Nenhuma mutação.\n");
    }

    TextDisplay.SetMessage(text);
}
}
